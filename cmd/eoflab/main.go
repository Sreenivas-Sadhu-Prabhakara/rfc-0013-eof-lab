package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"html/template"
	"io"
	"os"

	"example.com/rfc-go-labs/lab"
)

func main() {
	if err := run(os.Args[1:], os.Stdin, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string, input io.Reader, output io.Writer) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: eoflab encode | verify [-sha256 HEX] | demo")
	}
	switch args[0] {
	case "encode":
		if len(args) != 1 {
			return fmt.Errorf("usage: eoflab encode < input > framed")
		}
		return lab.EncodeEOF(output, input)
	case "verify":
		flags := flag.NewFlagSet("verify", flag.ContinueOnError)
		expectedHex := flags.String("sha256", "", "trusted expected payload digest (64 hex digits)")
		if err := flags.Parse(args[1:]); err != nil {
			return err
		}
		if flags.NArg() != 0 {
			return fmt.Errorf("unexpected positional arguments")
		}
		var expected *[sha256.Size]byte
		if *expectedHex != "" {
			decoded, err := hex.DecodeString(*expectedHex)
			if err != nil || len(decoded) != sha256.Size {
				return fmt.Errorf("sha256 must be 64 hex digits")
			}
			sum := [sha256.Size]byte(decoded)
			expected = &sum
		}
		report, err := lab.VerifyEOF(input, expected)
		if err != nil {
			return err
		}
		return json.NewEncoder(output).Encode(report)
	case "demo":
		if len(args) != 1 {
			return fmt.Errorf("usage: eoflab demo > report.html")
		}
		return demo(output)
	default:
		return fmt.Errorf("unknown command %q", args[0])
	}
}

type demoCase struct {
	Name     string
	Wire     []byte
	Expected *[sha256.Size]byte
}

type demoRow struct {
	Name   string
	Result string
	lab.EOFReport
}

func demo(output io.Writer) error {
	var encoded bytes.Buffer
	payload := []byte("statement-batch")
	if err := lab.EncodeEOF(&encoded, bytes.NewReader(payload)); err != nil {
		return err
	}
	wire := encoded.Bytes()
	expected := sha256.Sum256(payload)
	cases := []demoCase{
		{"Complete batch", wire, &expected},
		{"Empty file", make([]byte, 4), nil},
		{"Connection closed before marker", wire[:len(wire)-4], nil},
		{"Payload cut short", wire[:len(wire)-5], nil},
		{"Bytes after marker", append(bytes.Clone(wire), 1), nil},
		{"Premature marker with expected digest", make([]byte, 4), &expected},
	}
	rows := make([]demoRow, 0, len(cases))
	for _, scenario := range cases {
		report, err := lab.VerifyEOF(bytes.NewReader(scenario.Wire), scenario.Expected)
		result := "Accepted"
		if err != nil {
			result = err.Error()
		}
		rows = append(rows, demoRow{scenario.Name, result, report})
	}
	return template.Must(template.New("eof").Parse(demoPage)).Execute(output, rows)
}

